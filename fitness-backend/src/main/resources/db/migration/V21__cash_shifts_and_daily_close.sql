CREATE TABLE cash_shift (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 venue_id BIGINT NOT NULL REFERENCES venue(id),
 active_venue_id BIGINT UNIQUE REFERENCES venue(id),
 shift_no VARCHAR(255),
 business_date DATE,
 status VARCHAR(255) NOT NULL,
 version BIGINT NOT NULL,
 opened_by BIGINT NOT NULL REFERENCES sys_user(id),
 opened_at TIMESTAMP(6) NOT NULL,
 submitted_by BIGINT REFERENCES sys_user(id),
 closed_at TIMESTAMP(6),
 reviewed_by BIGINT REFERENCES sys_user(id),
 reviewed_at TIMESTAMP(6),
 review_reason VARCHAR(1000),
 note VARCHAR(1000),
 difference_reason VARCHAR(1000),
 handover_note VARCHAR(1000),
 baseline_payment_id BIGINT NOT NULL,
 opening_payment_id BIGINT NOT NULL,
 cutoff_payment_id BIGINT,
 ledger_fingerprint VARCHAR(255),
 system_receipts BIGINT NOT NULL,
 system_refunds BIGINT NOT NULL,
 actual_receipts BIGINT,
 actual_refunds BIGINT,
 CHECK ((status='OPEN' AND active_venue_id=venue_id) OR (status IN ('SUBMITTED','RETURNED','APPROVED') AND active_venue_id IS NULL))
);
CREATE TABLE cash_shift_channel (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 shift_id BIGINT NOT NULL REFERENCES cash_shift(id),
 channel VARCHAR(255) NOT NULL,
 system_receipts BIGINT NOT NULL,
 system_refunds BIGINT NOT NULL,
 actual_receipts BIGINT,
 actual_refunds BIGINT,
 UNIQUE (shift_id, channel)
);
CREATE TABLE cash_shift_payment (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 shift_id BIGINT NOT NULL REFERENCES cash_shift(id),
 payment_transaction_id BIGINT UNIQUE NOT NULL REFERENCES payment_transaction(id),
 transaction_no VARCHAR(255) NOT NULL,
 order_id BIGINT NOT NULL,
 transaction_type VARCHAR(255) NOT NULL,
 channel VARCHAR(255) NOT NULL,
 amount_cents BIGINT NOT NULL,
 occurred_at TIMESTAMP(6),
 operator_id BIGINT,
 carried_over BOOLEAN NOT NULL
);
CREATE TABLE cash_shift_event (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 shift_id BIGINT NOT NULL REFERENCES cash_shift(id),
 actor_id BIGINT NOT NULL REFERENCES sys_user(id),
 action VARCHAR(255) NOT NULL,
 content VARCHAR(1000),
 changes_json TEXT,
 request_key VARCHAR(255) NOT NULL,
 request_fingerprint VARCHAR(255) NOT NULL,
 created_at TIMESTAMP(6) NOT NULL,
 UNIQUE (actor_id, request_key)
);
CREATE INDEX ix_cash_shift_scope ON cash_shift(venue_id,business_date,status,id);
CREATE INDEX ix_cash_channel_shift ON cash_shift_channel(shift_id);
CREATE INDEX ix_cash_payment_shift ON cash_shift_payment(shift_id,payment_transaction_id);
CREATE INDEX ix_cash_event_shift ON cash_shift_event(shift_id,id);
